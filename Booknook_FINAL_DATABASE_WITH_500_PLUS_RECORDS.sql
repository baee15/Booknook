-- ============================================================
-- BUSINESS RULES HANDLED BY THE APPLICATION
-- ============================================================
-- Registered online customer = users + customers.
-- Walk-in/Messenger/Phone/SMS customer = customers only.
-- Advance reservation requires 50% deposit before confirmation.
-- Reserved end time stays fixed even if the customer arrives late.
-- Walk-in pays full base rate before check-in.
-- Walk-in expected end = check-in + selected rate duration.
-- Food is paid immediately.
-- Extension/overtime is settled before exit.
-- Availability is derived from confirmed reservations + active sessions.
-- One transaction can have multiple payments.
-- A payment uses Cash OR GCash, not both.
-- ============================================================



