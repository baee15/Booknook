        ON DELETE SET NULL,
    CONSTRAINT fk_sessions_customer
        FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_sessions_space
        FOREIGN KEY (space_id) REFERENCES study_spaces(space_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_sessions_rate
        FOREIGN KEY (rate_id) REFERENCES rate_plans(rate_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_sessions_checked_in_by
        FOREIGN KEY (checked_in_by_user_id) REFERENCES users(user_id)
        ON DELETE SET NULL,
    CONSTRAINT fk_sessions_checked_out_by
        FOREIGN KEY (checked_out_by_user_id) REFERENCES users(user_id)
        ON DELETE SET NULL
