DROP DATABASE IF EXISTS booknook_db;

CREATE DATABASE booknook_db
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE booknook_db;

-- 1. roles
CREATE TABLE roles (
    role_id TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    role_name VARCHAR(30) NOT NULL,
    description VARCHAR(255) NULL,
    PRIMARY KEY (role_id),
    UNIQUE KEY uq_roles_role_name (role_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 2. users
CREATE TABLE users (
    user_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    role_id TINYINT UNSIGNED NOT NULL,
    username VARCHAR(60) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    account_status ENUM('ACTIVE','INACTIVE') NOT NULL DEFAULT 'ACTIVE',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id),
    UNIQUE KEY uq_users_username (username),
    KEY idx_users_role_id (role_id),
    CONSTRAINT fk_users_role
        FOREIGN KEY (role_id) REFERENCES roles(role_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 3. customers
CREATE TABLE customers (
    customer_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id INT UNSIGNED NULL,
    first_name VARCHAR(60) NOT NULL,
    middle_name VARCHAR(60) NULL,
    last_name VARCHAR(60) NOT NULL,
    contact_number VARCHAR(30) NOT NULL,
    email VARCHAR(120) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (customer_id),
    UNIQUE KEY uq_customers_user_id (user_id),
    KEY idx_customers_contact_number (contact_number),
    CONSTRAINT fk_customers_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 4. audit_logs
CREATE TABLE audit_logs (
    log_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id INT UNSIGNED NOT NULL,
    action VARCHAR(100) NOT NULL,
    entity_name VARCHAR(80) NOT NULL,
    entity_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (log_id),
    KEY idx_audit_logs_user_id (user_id),
    CONSTRAINT fk_audit_logs_user
        FOREIGN KEY (user_id) REFERENCES users(user_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 5. space_types
CREATE TABLE space_types (
    space_type_id SMALLINT UNSIGNED NOT NULL AUTO_INCREMENT,
    type_name VARCHAR(60) NOT NULL,
    description VARCHAR(255) NULL,
    PRIMARY KEY (space_type_id),
    UNIQUE KEY uq_space_types_type_name (type_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 6. study_spaces
CREATE TABLE study_spaces (
    space_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    space_type_id SMALLINT UNSIGNED NOT NULL,
    space_name VARCHAR(80) NOT NULL,
    capacity SMALLINT UNSIGNED NOT NULL,
    operational_status ENUM('ACTIVE','MAINTENANCE','OUT_OF_SERVICE')
        NOT NULL DEFAULT 'ACTIVE',
    PRIMARY KEY (space_id),
    UNIQUE KEY uq_study_spaces_space_name (space_name),
    KEY idx_study_spaces_space_type_id (space_type_id),
    CONSTRAINT fk_study_spaces_type
        FOREIGN KEY (space_type_id) REFERENCES space_types(space_type_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 7. rate_periods
CREATE TABLE rate_periods (
    rate_period_id TINYINT UNSIGNED NOT NULL AUTO_INCREMENT,
    period_name VARCHAR(30) NOT NULL,
    start_time TIME NULL,
    end_time TIME NULL,
    description VARCHAR(255) NULL,
    PRIMARY KEY (rate_period_id),
    UNIQUE KEY uq_rate_periods_period_name (period_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 8. rate_plans
CREATE TABLE rate_plans (
    rate_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    space_type_id SMALLINT UNSIGNED NOT NULL,
    rate_period_id TINYINT UNSIGNED NOT NULL,
    rate_name VARCHAR(100) NOT NULL,
    duration_minutes SMALLINT UNSIGNED NOT NULL,
    base_price DECIMAL(10,2) NOT NULL,
    included_persons SMALLINT UNSIGNED NOT NULL DEFAULT 1,
    extension_hour_rate DECIMAL(10,2) NULL,
    additional_person_hour_rate DECIMAL(10,2) NULL,
    effective_from DATE NOT NULL,
    effective_to DATE NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (rate_id),
    UNIQUE KEY uq_rate_plan_version
        (space_type_id, rate_period_id, rate_name, effective_from),
    KEY idx_rate_plans_space_type_id (space_type_id),
    KEY idx_rate_plans_rate_period_id (rate_period_id),
    CONSTRAINT fk_rate_plans_space_type
        FOREIGN KEY (space_type_id) REFERENCES space_types(space_type_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_rate_plans_period
        FOREIGN KEY (rate_period_id) REFERENCES rate_periods(rate_period_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 9. reservations
CREATE TABLE reservations (
    reservation_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    customer_id INT UNSIGNED NOT NULL,
    space_id INT UNSIGNED NOT NULL,
    rate_id INT UNSIGNED NOT NULL,
    created_by_user_id INT UNSIGNED NOT NULL,
    reservation_channel ENUM('WEB','MESSENGER','PHONE','SMS','IN_PERSON') NOT NULL,
    reserved_party_size SMALLINT UNSIGNED NOT NULL,
    reserved_start_at DATETIME NOT NULL,
    reserved_end_at DATETIME NOT NULL,
    status ENUM('PENDING_DEPOSIT','CONFIRMED','CANCELLED','NO_SHOW','COMPLETED')
        NOT NULL DEFAULT 'PENDING_DEPOSIT',
    notes VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (reservation_id),
    KEY idx_reservations_customer_id (customer_id),
    KEY idx_reservations_space_id (space_id),
    KEY idx_reservations_rate_id (rate_id),
    KEY idx_reservations_created_by_user_id (created_by_user_id),
    KEY idx_reservations_schedule (space_id, reserved_start_at, reserved_end_at),
    CONSTRAINT fk_reservations_customer
        FOREIGN KEY (customer_id) REFERENCES customers(customer_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_space
        FOREIGN KEY (space_id) REFERENCES study_spaces(space_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_rate
        FOREIGN KEY (rate_id) REFERENCES rate_plans(rate_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_creator
        FOREIGN KEY (created_by_user_id) REFERENCES users(user_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 10. study_sessions
CREATE TABLE study_sessions (
    session_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    reservation_id BIGINT UNSIGNED NULL,
    customer_id INT UNSIGNED NOT NULL,
    space_id INT UNSIGNED NOT NULL,
    rate_id INT UNSIGNED NOT NULL,
    checked_in_by_user_id INT UNSIGNED NULL,
    checked_out_by_user_id INT UNSIGNED NULL,
    actual_party_size SMALLINT UNSIGNED NOT NULL,
    check_in_at DATETIME NULL,
    expected_end_at DATETIME NULL,
    check_out_at DATETIME NULL,
    status ENUM('PENDING','ACTIVE','COMPLETED','CANCELLED')
        NOT NULL DEFAULT 'PENDING',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (session_id),
    UNIQUE KEY uq_study_sessions_reservation_id (reservation_id),
    KEY idx_study_sessions_customer_id (customer_id),
    KEY idx_study_sessions_space_id (space_id),
    KEY idx_study_sessions_rate_id (rate_id),
    KEY idx_study_sessions_checked_in_by (checked_in_by_user_id),
    KEY idx_study_sessions_checked_out_by (checked_out_by_user_id),
