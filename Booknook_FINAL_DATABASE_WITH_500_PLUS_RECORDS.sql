-- 11. session_adjustments
CREATE TABLE session_adjustments (
    adjustment_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    session_id BIGINT UNSIGNED NOT NULL,
    recorded_by_user_id INT UNSIGNED NOT NULL,
    adjustment_type ENUM('EXTENSION','OVERTIME') NOT NULL,
    additional_minutes SMALLINT UNSIGNED NOT NULL,
    new_expected_end_at DATETIME NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (adjustment_id),
    KEY idx_session_adjustments_session_id (session_id),
    KEY idx_session_adjustments_recorded_by (recorded_by_user_id),
    CONSTRAINT fk_adjustments_session
        FOREIGN KEY (session_id) REFERENCES study_sessions(session_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_adjustments_recorder
        FOREIGN KEY (recorded_by_user_id) REFERENCES users(user_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 12. menu_items
CREATE TABLE menu_items (
    menu_item_id INT UNSIGNED NOT NULL AUTO_INCREMENT,
    item_name VARCHAR(100) NOT NULL,
    category VARCHAR(60) NULL,
    price DECIMAL(10,2) NOT NULL,
    description VARCHAR(255) NULL,
    is_available TINYINT(1) NOT NULL DEFAULT 1,
    PRIMARY KEY (menu_item_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 13. transactions
CREATE TABLE transactions (
    transaction_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    reservation_id BIGINT UNSIGNED NULL,
    session_id BIGINT UNSIGNED NULL,
    created_by_user_id INT UNSIGNED NOT NULL,
    transaction_status ENUM('OPEN','COMPLETED','CANCELLED')
        NOT NULL DEFAULT 'OPEN',
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at DATETIME NULL,
    PRIMARY KEY (transaction_id),
    UNIQUE KEY uq_transactions_reservation_id (reservation_id),
    UNIQUE KEY uq_transactions_session_id (session_id),
    KEY idx_transactions_created_by_user_id (created_by_user_id),
    CONSTRAINT fk_transactions_reservation
        FOREIGN KEY (reservation_id) REFERENCES reservations(reservation_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_transactions_session
        FOREIGN KEY (session_id) REFERENCES study_sessions(session_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_transactions_creator
        FOREIGN KEY (created_by_user_id) REFERENCES users(user_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 14. transaction_items
CREATE TABLE transaction_items (
    transaction_item_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    transaction_id BIGINT UNSIGNED NOT NULL,
    rate_id INT UNSIGNED NULL,
    adjustment_id BIGINT UNSIGNED NULL,
    menu_item_id INT UNSIGNED NULL,
    charge_type ENUM('BASE_PASS','ADDITIONAL_PERSON','EXTENSION','OVERTIME','MENU_ITEM') NOT NULL,
    quantity DECIMAL(10,2) NOT NULL DEFAULT 1.00,
    unit_price DECIMAL(10,2) NOT NULL,
    line_amount DECIMAL(12,2) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (transaction_item_id),
    UNIQUE KEY uq_transaction_items_adjustment_id (adjustment_id),
    KEY idx_transaction_items_transaction_id (transaction_id),
    KEY idx_transaction_items_rate_id (rate_id),
    KEY idx_transaction_items_menu_item_id (menu_item_id),
    CONSTRAINT fk_transaction_items_transaction
        FOREIGN KEY (transaction_id) REFERENCES transactions(transaction_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_transaction_items_rate
        FOREIGN KEY (rate_id) REFERENCES rate_plans(rate_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_transaction_items_adjustment
        FOREIGN KEY (adjustment_id) REFERENCES session_adjustments(adjustment_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_transaction_items_menu
        FOREIGN KEY (menu_item_id) REFERENCES menu_items(menu_item_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 15. payments
CREATE TABLE payments (
    payment_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    transaction_id BIGINT UNSIGNED NOT NULL,
    recorded_by_user_id INT UNSIGNED NOT NULL,
    amount_paid DECIMAL(10,2) NOT NULL,
    payment_status ENUM('PENDING','VERIFIED','VOID') NOT NULL,
    paid_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (payment_id),
    KEY idx_payments_transaction_id (transaction_id),
    KEY idx_payments_recorded_by_user_id (recorded_by_user_id),
    CONSTRAINT fk_payments_transaction
        FOREIGN KEY (transaction_id) REFERENCES transactions(transaction_id)
        ON DELETE RESTRICT,
    CONSTRAINT fk_payments_recorder
        FOREIGN KEY (recorded_by_user_id) REFERENCES users(user_id)
        ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 16. cash_payments
CREATE TABLE cash_payments (
    payment_id BIGINT UNSIGNED NOT NULL,
    cash_received DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (payment_id),
    CONSTRAINT fk_cash_payment
        FOREIGN KEY (payment_id) REFERENCES payments(payment_id)
        ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- 17. gcash_payments
CREATE TABLE gcash_payments (
    payment_id BIGINT UNSIGNED NOT NULL,
    reference_number VARCHAR(100) NOT NULL,
    sender_name VARCHAR(120) NULL,
    verified_by_user_id INT UNSIGNED NULL,
    verified_at DATETIME NULL,
    PRIMARY KEY (payment_id),
    UNIQUE KEY uq_gcash_reference_number (reference_number),
    KEY idx_gcash_verified_by_user_id (verified_by_user_id),
    CONSTRAINT fk_gcash_payment
        FOREIGN KEY (payment_id) REFERENCES payments(payment_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_gcash_verifier
        FOREIGN KEY (verified_by_user_id) REFERENCES users(user_id)
        ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

